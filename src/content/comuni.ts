export interface Comune {
  id: string
  name: string
  prov: string
  region: string
  lat: number
  lon: number
  pop: number
}

/** "Cava de' Tirreni" → "cava-de-tirreni", "Forlì" → "forli" */
export function normalize(s: string): string {
  return s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
}

export const slugify = (s: string) => normalize(s).replace(/ /g, '-')

export const COMUNI: Comune[] = ROWS.map(([name, prov, region, lat, lon, pop]) => ({
  id: slugify(name),
  name,
  prov,
  region,
  lat,
  lon,
  pop,
}))

const BY_ID = new Map(COMUNI.map((c) => [c.id, c]))
export const comuneById = (id: string): Comune | undefined => BY_ID.get(id)

export const REGIONS = [...new Set(COMUNI.map((c) => c.region))]
